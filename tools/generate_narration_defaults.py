"""Validate canonical narration JSON and generate compiled fallback data.

JSON is the sole authored prose source. Generated Papyrus is never hand-edited.
"""
from pathlib import Path
import json,re,hashlib

ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'SKSE/Plugins/StorageUtilData/MMEAlerts/Narration'

def unique(pairs):
    obj={}
    for k,v in pairs:
        if k in obj:raise ValueError('Duplicate JSON key: '+k)
        obj[k]=v
    return obj

def literal(s):return json.dumps(s,ensure_ascii=False)
def tokens(s):
    return {('actor' if t in ['ACTOR','ActorName'] else t) for t in re.findall(r'\{([^{}]+)\}',s)}

def validate_document(obj,routes,file):
    if obj.get('schemaVersion')!=1:raise ValueError('Unsupported schema: '+file)
    if set(obj['routes'])!=set(routes):raise ValueError('Missing/unknown default routes: '+file)
    for key,meta in routes.items():
        value=obj['routes'][key]['template'];pool=value if isinstance(value,list) else [value]
        if not pool:raise ValueError('Empty pool: '+key)
        for text in pool:
            if not isinstance(text,str) or not text.strip():raise ValueError('Empty/non-string template: '+key)
            if tokens(text)!=set(meta['tokens']):raise ValueError('Unexpected/missing tokens: '+key)
            if re.search(r'[{}]',re.sub(r'\{[^{}]+\}', '', text)):raise ValueError('Invalid braces: '+key)

def generate():
    schema=json.loads((ROOT/'tools/narration-schema.json').read_text(encoding='utf-8-sig'))
    values={};hashes={}
    for file,routes in schema.items():
        path=DATA/(file+'.json');obj=json.loads(path.read_text(encoding='utf-8-sig'),object_pairs_hook=unique)
        validate_document(obj,routes,file)
        for key in routes:values[(file,key)]=obj['routes'][key]['template']
        hashes[file]=hashlib.sha256(path.read_bytes()).hexdigest()
    lines=['; Generated by tools/generate_narration_defaults.py. Edit Narration/*.json.','Scriptname MMENarrationDefaults Hidden','']
    def function(header,body):lines.extend([header,*body,'EndFunction',''])
    function('Int Function FileCount() Global',[f'    Return {len(schema)}'])
    function('String Function FileName(Int index) Global',[x for i,f in enumerate(schema) for x in [f'    If index == {i}',f'        Return "{f}"','    EndIf']]+['    Return ""'])
    function('Int Function RouteCount(String fileKey) Global',
        [x for file,routes in schema.items() for x in [f'    If fileKey == "{file}"',f'        Return {len(routes)}','    EndIf']]+['    Return 0'])
    function('String Function RouteKey(String fileKey, Int index) Global',
        [x for file,routes in schema.items() for i,key in enumerate(routes) for x in [f'    If fileKey == "{file}" && index == {i}',f'        Return "{key}"','    EndIf']]+['    Return ""'])
    function('String Function Template(String fileKey, String routeKey, Int index = 0) Global',
        [x for (file,key),value in values.items() for x in [f'    If fileKey == "{file}" && routeKey == "{key}"',*([f'        If index == {i}\n            Return {literal(v)}\n        EndIf' for i,v in enumerate(value)] if isinstance(value,list) else [f'        Return {literal(value)}']),'    EndIf']]+['    Return ""'])
    function('Int Function PoolCount(String fileKey, String routeKey) Global',
        [x for (file,key),value in values.items() if isinstance(value,list) for x in [f'    If fileKey == "{file}" && routeKey == "{key}"',f'        Return {len(value)}','    EndIf']]+['    Return 0'])
    function('String Function Tokens(String fileKey, String routeKey) Global',
        [x for file,routes in schema.items() for key,meta in routes.items() for x in [f'    If fileKey == "{file}" && routeKey == "{key}"',f'        Return "|'+ '|'.join(meta['tokens'])+'|"','    EndIf']]+['    Return ""'])
    legacy=json.loads((ROOT/'tools/narration-legacy-map.json').read_text(encoding='utf-8-sig'))
    function('Int Function LegacyCount() Global',[f'    Return {len(legacy)}'])
    for field,name in [('file','TargetFile'),('key','TargetRoute'),('legacyFile','LegacyFile'),('legacyPath','LegacyPath'),('legacyKey','LegacyKey')]:
        function(f'String Function {name}(Int index) Global',[x for i,row in enumerate(legacy) for x in [f'    If index == {i}',f'        Return {literal(row[field])}','    EndIf']]+['    Return ""'])
    (ROOT/'Source/Scripts/MMENarrationDefaults.psc').write_text('\n'.join(lines),encoding='utf-8')
    (DATA/'RouteReference.txt').write_text('NARRATION ROUTES AND PLACEHOLDERS\n\n'+''.join(file+'.json\n'+''.join('  '+key+': '+(', '.join('{'+t+'}' for t in meta['tokens']) or '(no placeholders)')+'\n' for key,meta in routes.items())+'\n' for file,routes in schema.items()),encoding='utf-8')
    (ROOT/'build/diagnostics').mkdir(parents=True,exist_ok=True)
    (ROOT/'build/diagnostics/narration-default-hashes.json').write_text(json.dumps(hashes,indent=2)+'\n')
    print(f'PASS: {len(schema)} narration files; {len(values)} routes; generated fallback script and token reference')

if __name__=='__main__':generate()
