"""Generate the proof editor's native fallback from the authored lore JSON."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'SKSE/Plugins/StorageUtilData/MMEAlerts/Narration/Lore.json'
text = json.loads(source.read_text(encoding='utf-8-sig'))['routes']['milk_lore']['template']
output = ROOT / 'include/LoreEditorDefaults.h'
output.write_text('// Generated by tools/generate_lore_editor_defaults.py; do not edit.\n'
                  '#pragma once\nnamespace MME::Narration {\n'
                  'inline constexpr auto kGeneralLoreDefault = '
                  + json.dumps(text, ensure_ascii=True) + ';\n}\n', encoding='utf-8')
